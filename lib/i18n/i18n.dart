import 'dart:ui' show PlatformDispatcher;

import 'package:flutter/foundation.dart';
import 'package:shared_preferences/shared_preferences.dart';

/// App language state. Defaults to the device language when supported,
/// otherwise English. The user can override it in Settings.
class I18n extends ChangeNotifier {
  static final I18n instance = I18n._();
  I18n._();

  static const supported = ['en', 'es', 'ca', 'de'];
  static const names = {
    'en': 'English',
    'es': 'Español',
    'ca': 'Català',
    'de': 'Deutsch',
  };

  String _code = 'en';
  String get code => _code;

  Future<void> load(SharedPreferences prefs) async {
    final saved = prefs.getString('app_lang');
    if (saved != null && supported.contains(saved)) {
      _code = saved;
    } else {
      final device = PlatformDispatcher.instance.locale.languageCode;
      _code = supported.contains(device) ? device : 'en';
    }
    notifyListeners();
  }

  Future<void> setCode(String code) async {
    if (!supported.contains(code)) return;
    _code = code;
    notifyListeners();
    final prefs = await SharedPreferences.getInstance();
    await prefs.setString('app_lang', code);
  }
}

